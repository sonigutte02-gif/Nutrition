# ─── Guardrail: Check for harmful content ─────────────────────────────────────
def is_harmful(text: str) -> bool:
    text_lower = text.lower()
    return any(kw in text_lower for kw in HARMFUL_KEYWORDS)


def needs_medical_redirect(text: str) -> bool:
    text_lower = text.lower()
    return any(kw in text_lower for kw in MEDICAL_REDIRECT_KEYWORDS)


def sanitize_output(text: str) -> str:
    """Remove any model artifacts or incomplete tags."""
    text = re.sub(r"<\|.*?\|>", "", text)
    text = re.sub(r"\[INST\]|\[/INST\]|<<SYS>>|<</SYS>>", "", text)
    return text.strip()


