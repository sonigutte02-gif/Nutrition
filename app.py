@app.route("/api/generate-plan", methods=["POST"])
def generate_plan():
    data = request.get_json()
    if not data:
        return jsonify({"error": "No data provided"}), 400

    # ── Validate required fields ──
    required = ["name", "age", "diet_preference", "city", "country"]
    missing = [f for f in required if not data.get(f)]
    if missing:
        return jsonify({"error": f"Missing required fields: {', '.join(missing)}"}), 400

    # ── Validate age ──
    try:
        age = int(data["age"])
        if not (1 <= age <= 120):
            raise ValueError
    except (ValueError, TypeError):
        return jsonify({"error": "Please provide a valid age between 1 and 120."}), 400

    # ── Guardrail: harmful input check ──
    combined_input = " ".join(str(v) for v in data.values())
    if is_harmful(combined_input):
        return jsonify({
            "error": "Your input contains content that cannot be processed. "
                     "Please consult a healthcare professional directly."
        }), 400

    if needs_medical_redirect(combined_input):
        return jsonify({
            "warning": "Some aspects of your query require professional medical advice. "
                       "Please consult your doctor or pharmacist for medication-related questions."
        }), 200

    # ── Store user context in session ──
    session["user_data"] = data

    # ── Call IBM Granite ──
    try:
        model  = get_granite_model()
        prompt = build_nutrition_prompt(data)
        result = model.generate_text(prompt=prompt)
        plan   = sanitize_output(result)
        plan  += DISCLAIMER
        return jsonify({"plan": plan, "status": "success"})
    except Exception as e:
        return jsonify({"error": f"AI service error: {str(e)}"}), 500


@app.route("/api/chat", methods=["POST"])
def chat():
    data = request.get_json()
    if not data or not data.get("message"):
        return jsonify({"error": "No message provided"}), 400

    user_message = data["message"].strip()
    user_context = session.get("user_data", {})

    # ── Guardrail ──
    if is_harmful(user_message):
        return jsonify({
            "reply": "⚠️ I'm unable to respond to that query. "
                     "If you're in distress, please contact a healthcare professional or helpline immediately."
        })

    if needs_medical_redirect(user_message):
        return jsonify({
            "reply": "⚠️ That query involves specific medical decisions. "
                     "Please consult your doctor or a licensed pharmacist for personalised guidance."
        })

    try:
        model  = get_granite_model()
        prompt = build_chat_prompt(user_message, user_context)
        result = model.generate_text(prompt=prompt)
        reply  = sanitize_output(result)
        reply += "\n\n*— NutriGuide AI (powered by IBM Granite)*"
        return jsonify({"reply": reply, "status": "success"})
    except Exception as e:
        return jsonify({"error": f"AI service error: {str(e)}"}), 500


